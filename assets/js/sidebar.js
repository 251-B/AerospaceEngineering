/*!
 * Aerospace Engineering Study Portal: side menu (left drawer).
 *
 * Loaded on every page by assets/js/theme.js, after assets/data/nav.js (no page carries its own
 * <script> tag for it); the script adds its own stylesheet (assets/css/sidebar.css). Skipped in the
 * PDF print mode (?print=...), and hidden by @media print.
 *
 *   - button: a "menu" button as the first item of the page header (or a floating one when the page
 *     has no header);
 *   - drawer: slides in from the left over the page, closed by default on every screen size. It lists
 *     the whole portal: the five subjects as collapsible groups, each with Theory and Problems (and
 *     the PDF and exam pages). The current subject, area and page are open and marked;
 *   - sections: under the current page, its own sections (h2 headings on theory pages, problem cards
 *     on problem pages) are listed and the one being read is highlighted while the page scrolls.
 *
 * The tree comes from assets/data/nav.js (window.AE_NAV), generated by tools/build_nav.py from
 * tools/nav.json. Paths in it start at the portal root and are resolved against this script's own
 * URL, so they work from any page depth and over file://.
 *
 * Storage: 'ae_nav' (JSON: { open: [group keys] }), the groups the visitor opened or closed.
 * API: window.AESidebar = { KEY, open, close, isOpen }
 */
(function () {
  'use strict';

  if (window.AESidebar) return;
  if (new URLSearchParams(location.search).has('print')) return;

  var SCRIPT = document.currentScript;
  var KEY = 'ae_nav';
  var ROOT = SCRIPT && SCRIPT.src ? SCRIPT.src.replace(/assets\/js\/sidebar\.js(\?.*)?$/, '') : '';
  var nav = window.AE_NAV && Array.isArray(window.AE_NAV.subjects) ? window.AE_NAV : null;

  /* ---------------------------------------------------------------- helpers */
  function el(tag, className, text) {
    var node = document.createElement(tag);
    if (className) node.className = className;
    if (text) node.textContent = text;
    return node;
  }

  function svg(inner, size) {
    var s = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
    s.setAttribute('viewBox', '0 0 24 24');
    s.setAttribute('width', size);   // sized without the stylesheet too
    s.setAttribute('height', size);
    s.setAttribute('aria-hidden', 'true');
    s.innerHTML = inner;
    return s;
  }

  function pathOf(url) {
    var path;
    try { path = decodeURIComponent(new URL(url, location.href).pathname); } catch (e) { return ''; }
    return path.replace(/\/$/, '/index.html');
  }

  function hrefOf(path) { return ROOT + encodeURI(path); }

  var HERE = pathOf(location.href);

  /* ---------------------------------------------------------------- open/closed groups */
  var openKeys = null;   // null until read; also the in-memory copy when storage is blocked

  function readOpen() {
    if (openKeys) return openKeys;
    openKeys = [];
    try {
      var s = JSON.parse(localStorage.getItem(KEY) || 'null');
      if (s && Array.isArray(s.open)) openKeys = s.open.filter(function (k) { return typeof k === 'string'; });
    } catch (e) { /* blocked or corrupted: start with nothing remembered */ }
    return openKeys;
  }

  function writeOpen() {
    try { localStorage.setItem(KEY, JSON.stringify({ open: openKeys })); } catch (e) { /* keep it in memory only */ }
  }

  function setGroup(key, open) {
    var keys = readOpen();
    var i = keys.indexOf(key);
    if (open && i < 0) keys.push(key);
    if (!open && i >= 0) keys.splice(i, 1);
    writeOpen();
  }

  /* ---------------------------------------------------------------- tree */
  var ui = {};
  var currentLink = null;

  // A collapsible group: a header button that shows or hides its list.
  function group(key, title, className, opts) {
    var wrap = el('div', 'ae-nav__group ' + className);
    var head = el('button', 'ae-nav__toggle');
    head.type = 'button';
    if (opts && opts.accent) {
      var dot = el('span', 'ae-nav__dot');
      dot.style.setProperty('--dot', opts.accent);
      head.appendChild(dot);
    }
    head.appendChild(el('span', 'ae-nav__toggle-label', title));
    head.appendChild(svg('<path d="M9 6l6 6-6 6"/>', 14));
    var body = el('div', 'ae-nav__body');
    var id = 'aeNav-' + key.replace(/[^a-z0-9]+/gi, '-');
    body.id = id;
    head.setAttribute('aria-controls', id);
    var isOpen = (opts && opts.forceOpen) || readOpen().indexOf(key) >= 0;
    function apply(open) {
      wrap.classList.toggle('is-open', open);
      head.setAttribute('aria-expanded', open ? 'true' : 'false');
      body.hidden = !open;
    }
    apply(isOpen);
    head.addEventListener('click', function () {
      var open = !wrap.classList.contains('is-open');
      apply(open);
      setGroup(key, open);
    });
    wrap.appendChild(head);
    wrap.appendChild(body);
    wrap.aeBody = body;
    wrap.aeOpen = apply;
    return wrap;
  }

  function link(path, label, className) {
    var a = el('a', 'ae-nav__link' + (className ? ' ' + className : ''), label);
    a.href = hrefOf(path);
    if (pathOf(a.href) === HERE) {
      a.classList.add('is-current');
      a.setAttribute('aria-current', 'page');
      currentLink = a;
    }
    return a;
  }

  function containsCurrent(node) {
    if (pathOf(hrefOf(node.href)) === HERE) return true;
    return (node.children || []).some(containsCurrent);
  }

  function pageItem(subjectSlug, area, page) {
    var item = el('div', 'ae-nav__item');
    if (!page.children || !page.children.length) {
      item.appendChild(link(page.href, page.label));
      return item;
    }
    // A page with sub-pages (Fluid Mechanics topic 3): its own link plus a nested group.
    var key = subjectSlug + '/' + area + '/' + page.href;
    var sub = group(key, page.label, 'ae-nav__group--sub', { forceOpen: containsCurrent(page) });
    var head = sub.firstChild;
    var own = link(page.href, 'Overview', 'ae-nav__link--lead');
    sub.aeBody.appendChild(own);
    page.children.forEach(function (c) { sub.aeBody.appendChild(pageItem(subjectSlug, area, c)); });
    head.classList.toggle('has-current', containsCurrent(page));
    item.appendChild(sub);
    return item;
  }

  function buildTree() {
    var tree = el('nav', 'ae-nav__tree');
    tree.setAttribute('aria-label', 'Portal');
    tree.appendChild(link('index.html', 'Portal home', 'ae-nav__home'));

    nav.subjects.forEach(function (subject) {
      var inSubject = HERE.indexOf('/subjects/' + subject.slug + '/') >= 0;
      var g = group('s/' + subject.slug, subject.name, 'ae-nav__group--subject', { accent: subject.accent, forceOpen: inSubject });
      g.firstChild.classList.toggle('has-current', inSubject);

      subject.groups.forEach(function (area) {
        var inArea = HERE.indexOf('/subjects/' + subject.slug + '/' + area.id + '/') >= 0;
        var ag = group('a/' + subject.slug + '/' + area.id, area.label, 'ae-nav__group--area', { forceOpen: inArea });
        ag.aeBody.appendChild(link(area.href, 'Overview', 'ae-nav__link--lead'));
        area.pages.forEach(function (p) { ag.aeBody.appendChild(pageItem(subject.slug, area.id, p)); });
        g.aeBody.appendChild(ag);
      });
      (subject.extras || []).forEach(function (x) { g.aeBody.appendChild(link(x.href, x.label, 'ae-nav__link--extra')); });
      tree.appendChild(g);
    });
    return tree;
  }

  /* ---------------------------------------------------------------- sections of the current page */
  var sectionLinks = [];
  var spy = null;

  function headingText(node) {
    var clone = node.cloneNode(true);
    Array.prototype.forEach.call(clone.querySelectorAll('.katex-mathml, .src-cite-pop, script, style'), function (n) { n.remove(); });
    var num = clone.querySelector('.section-num');
    var prefix = '';
    if (num) { prefix = num.textContent.trim() + ' '; num.remove(); }
    var text = (prefix + clone.textContent).replace(/\s+/g, ' ').replace(/\s*\[[^\]]*\]\s*$/, '').trim();
    return text.length > 90 ? text.slice(0, 87).trim() + '…' : text;
  }

  function slug(text) {
    return 'sec-' + text.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, 40);
  }

  function collectSections() {
    var out = [];
    var cards = document.querySelectorAll('.problem-card[id]');
    if (cards.length) {
      Array.prototype.forEach.call(cards, function (card) {
        var title = card.querySelector('.problem-title') || card.querySelector('h2, h3');
        var text = title ? headingText(title) : '';
        if (text) out.push({ id: card.id, text: text, target: card });
      });
      return out;
    }
    var scope = document.querySelector('main') || document.body;
    var used = {};
    Array.prototype.forEach.call(scope.querySelectorAll('h2'), function (h) {
      if (h.closest('.toc-card, .src-panel, .ae-nav, nav, aside, .exam-box, [class*="ask-ai"], [class*="upd-"], [class*="fl-"], [class*="pm-"], [class*="surface-"]')) return;
      var text = headingText(h);
      if (!text) return;
      if (!h.id) {   // pages without ids get one, so the menu can jump to the heading
        var base = slug(text), id = base, n = 2;
        while (used[id] || document.getElementById(id)) id = base + '-' + n++;
        h.id = id;
      }
      used[h.id] = true;
      out.push({ id: h.id, text: text, target: h });
    });
    return out;
  }

  function buildSections() {
    if (!currentLink || !ui.tree) return;
    var old = ui.tree.querySelector('.ae-nav__sections');
    if (old) old.remove();
    if (spy) { spy.disconnect(); spy = null; }
    sectionLinks = [];
    var sections = collectSections();
    // The portal home is a gallery, and a single heading is not worth a list.
    if (currentLink.classList.contains('ae-nav__home') || sections.length < 2) return;

    var list = el('ol', 'ae-nav__sections');
    list.setAttribute('aria-label', 'On this page');
    sections.forEach(function (s) {
      var li = el('li');
      var a = el('a', 'ae-nav__link ae-nav__link--section', s.text);
      a.href = '#' + s.id;
      li.appendChild(a);
      list.appendChild(li);
      sectionLinks.push({ a: a, target: s.target });
    });
    currentLink.parentNode.insertBefore(list, currentLink.nextSibling);

    if (!('IntersectionObserver' in window)) return;
    var visible = [];
    spy = new IntersectionObserver(function (entries) {
      entries.forEach(function (e) {
        var i = visible.indexOf(e.target);
        if (e.isIntersecting && i < 0) visible.push(e.target);
        if (!e.isIntersecting && i >= 0) visible.splice(i, 1);
      });
      var first = null;
      sectionLinks.forEach(function (s) { if (!first && visible.indexOf(s.target) >= 0) first = s; });
      sectionLinks.forEach(function (s) {
        var on = s === first;
        s.a.classList.toggle('is-active', on);
        if (on) s.a.setAttribute('aria-current', 'location'); else s.a.removeAttribute('aria-current');
      });
    }, { rootMargin: '-15% 0px -70% 0px' });
    sectionLinks.forEach(function (s) { spy.observe(s.target); });
  }

  /* ---------------------------------------------------------------- drawer */
  function isOpen() { return !!ui.drawer && ui.drawer.classList.contains('is-open'); }

  function openDrawer() {
    if (!ui.drawer || isOpen()) return;
    // One floating panel at a time, like the study timer, Focus Lab and the updates panel.
    ['AEPomodoro', 'AEFocusLab', 'AEUpdates'].forEach(function (name) {
      if (window[name] && typeof window[name].close === 'function') window[name].close();
    });
    ui.drawer.hidden = false;
    ui.backdrop.hidden = false;
    void ui.drawer.offsetWidth;   // lets the slide-in start from its closed position
    ui.drawer.classList.add('is-open');
    ui.backdrop.classList.add('is-open');
    ui.button.setAttribute('aria-expanded', 'true');
    ui.button.setAttribute('aria-label', 'Close menu');
    document.documentElement.classList.add('ae-nav-lock');
    if (currentLink) currentLink.scrollIntoView({ block: 'center' });
    ui.drawer.focus({ preventScroll: true });
  }

  function closeDrawer(returnFocus) {
    if (!isOpen()) return;
    ui.drawer.classList.remove('is-open');
    ui.backdrop.classList.remove('is-open');
    ui.button.setAttribute('aria-expanded', 'false');
    ui.button.setAttribute('aria-label', 'Open menu');
    document.documentElement.classList.remove('ae-nav-lock');
    var done = function () {
      if (!isOpen()) { ui.drawer.hidden = true; ui.backdrop.hidden = true; }
    };
    setTimeout(done, 220);   // after the slide-out; a reopened drawer is left alone
    if (returnFocus) ui.button.focus();
  }

  function focusables() {
    return Array.prototype.filter.call(ui.drawer.querySelectorAll('a[href], button'), function (n) {
      return n.offsetParent !== null;
    });
  }

  function onKeydown(event) {
    if (!isOpen()) return;
    if (event.key === 'Escape') {
      event.stopPropagation();
      closeDrawer(true);
      return;
    }
    if (event.key !== 'Tab') return;
    // The drawer is modal: Tab wraps inside it instead of walking into the page behind.
    var items = focusables();
    if (!items.length) return;
    var first = items[0], last = items[items.length - 1];
    var inside = ui.drawer.contains(document.activeElement);
    if (event.shiftKey && (document.activeElement === first || document.activeElement === ui.drawer || !inside)) {
      event.preventDefault();
      last.focus();
    } else if (!event.shiftKey && (document.activeElement === last || !inside)) {
      event.preventDefault();
      first.focus();
    }
  }

  function placeButton(button) {
    var toggle = document.getElementById('themeToggle');
    var host = toggle && toggle.closest('.header-inner, .back-bar-inner, .top, .site-header, .header-container, header');
    if (host) {
      host.insertBefore(button, host.firstChild);
      return;
    }
    button.classList.add('ae-nav-btn--float');
    document.body.appendChild(button);
  }

  function build() {
    if (document.getElementById('sidebarButton') || !nav) return;

    var button = el('button', 'ae-nav-btn');
    button.type = 'button';
    button.id = 'sidebarButton';
    button.setAttribute('aria-haspopup', 'dialog');
    button.setAttribute('aria-expanded', 'false');
    button.setAttribute('aria-controls', 'sidebarDrawer');
    button.setAttribute('aria-label', 'Open menu');
    button.title = 'Menu';
    button.appendChild(svg('<path d="M4 7h16M4 12h16M4 17h16"/>', 18));
    placeButton(button);

    var backdrop = el('div', 'ae-nav-backdrop');
    backdrop.hidden = true;
    var drawer = el('aside', 'ae-nav');
    drawer.id = 'sidebarDrawer';
    drawer.setAttribute('role', 'dialog');
    drawer.setAttribute('aria-modal', 'true');
    drawer.setAttribute('aria-label', 'Portal menu');
    drawer.tabIndex = -1;
    drawer.hidden = true;   // hidden without the stylesheet too

    var head = el('div', 'ae-nav__head');
    head.appendChild(el('span', 'ae-nav__title', 'Study Portal'));
    var close = el('button', 'ae-nav__close');
    close.type = 'button';
    close.setAttribute('aria-label', 'Close menu');
    close.appendChild(svg('<path d="M6 6l12 12M18 6L6 18"/>', 16));
    head.appendChild(close);

    ui = { button: button, drawer: drawer, backdrop: backdrop };
    ui.tree = buildTree();
    drawer.appendChild(head);
    drawer.appendChild(ui.tree);
    document.body.appendChild(backdrop);
    document.body.appendChild(drawer);

    button.addEventListener('click', function () { if (isOpen()) closeDrawer(true); else openDrawer(); });
    close.addEventListener('click', function () { closeDrawer(true); });
    backdrop.addEventListener('click', function () { closeDrawer(false); });
    drawer.addEventListener('click', function (event) {
      var a = event.target.closest && event.target.closest('a[href]');
      if (a) closeDrawer(false);   // the page changes, or scrolls to the section: either way the menu is done
    });
    document.addEventListener('keydown', onKeydown);

    buildSections();
    // Formulas are typeset after load and can change a heading's text: list the sections again.
    window.addEventListener('load', buildSections);
  }

  /* ---------------------------------------------------------------- boot */
  function addStylesheet() {
    if (!SCRIPT || !SCRIPT.src || document.querySelector('link[href*="sidebar.css"]')) return;
    var linkEl = document.createElement('link');
    linkEl.rel = 'stylesheet';
    linkEl.href = SCRIPT.src.replace(/js\/sidebar\.js(\?.*)?$/, 'css/sidebar.css');
    document.head.appendChild(linkEl);
  }

  addStylesheet();
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', build);
  else build();

  window.AESidebar = {
    KEY: KEY,
    open: openDrawer,
    close: function () { closeDrawer(false); },
    isOpen: isOpen
  };
})();
