#!/usr/bin/env python3
"""Build a subject's formula sheet page from its vault note.

The note (`vault/<subject>/Formula Sheet - <Subject>.md`) is the source of truth; this tool rewrites
the block between `<!-- FORMULA-SHEET:START -->` and `<!-- FORMULA-SHEET:END -->` of
`subjects/<slug>/formula-sheet/index.html`. The rest of the page (head, toolbar, print layout,
script) is hand-written.

Note dialect (plain Obsidian Markdown):
    ## Unit 2 — First-order ODEs             one section per unit (h2, gets an id)
    Pages: Theory=teoria/topic-2.html; Problems=problemas/topic-2-problems.html
    ### Derivation: The integrating factor    one card; the kind is one of KINDS
    In short: one or two lines                 summary of a Derivation card (shown when it is folded)
    | Step | Why |                             a table with this header is a step-by-step grid:
    | --- | --- |                              math on the left, the reason on the right
    $$ ... $$, - bullets, 1. numbered lists, other tables, paragraphs, **bold**, *italic*, `code`
Anything before the first `## ` (title, intro) stays in the vault only. Inside tables write
\\lvert / \\rvert instead of a bare pipe.

Usage:
    python tools/build_formula_sheet.py            # rewrite the pages
    python tools/build_formula_sheet.py --check    # exit 1 if a page is stale
"""
import argparse
import html
import pathlib
import re
import sys

SHEETS = {
    "advanced-maths": "vault/04 - Advanced Maths/Formula Sheet - Advanced Maths.md",
    "engineering-mechanics": "vault/03 - Engineering Mechanics/Formula Sheet - Engineering Mechanics.md",
}
START = "<!-- FORMULA-SHEET:START (generated by tools/build_formula_sheet.py; edit the vault note) -->"
END = "<!-- FORMULA-SHEET:END -->"
KINDS = {
    "Pattern": "pattern", "Definition": "theorem", "Theorem": "theorem", "Derivation": "derivation",
    "Algorithm": "algorithm", "Trap": "trap", "Interpretation": "pattern", "Table": "pattern",
    "Prerequisite": "prereq",
}
_MATH = re.compile(r"\$\$.+?\$\$|\$[^$\n]+?\$", re.S)


def slugify(text):
    text = re.sub(r"\$[^$]*\$", "", text)
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")[:60] or "item"


def inline(text):
    """Escape text and apply inline Markdown, leaving math spans untouched."""
    maths = []

    def keep(m):
        maths.append(m.group(0))
        return f"\x00{len(maths) - 1}\x00"

    text = html.escape(_MATH.sub(keep, text), quote=False)
    text = re.sub(r"\[\[(?:[^\]|]*\|)?([^\]]+)\]\]", r"\1", text)
    text = re.sub(r"`([^`]+)`", r"<code>\1</code>", text)
    text = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", text)
    text = re.sub(r"(?<![\w*])\*(?!\s)(.+?)(?<!\s)\*(?![\w*])", r"<em>\1</em>", text)
    return re.sub(r"\x00(\d+)\x00", lambda m: html.escape(maths[int(m.group(1))], quote=False), text)


def _cells(line):
    return [c.strip() for c in line.strip().strip("|").split("|")]


def render_blocks(lines):
    """Render the body of a card (list of lines) to HTML."""
    out, i = [], 0
    while i < len(lines):
        line = lines[i].rstrip()
        s = line.strip()
        if not s or s == "---":
            i += 1
        elif s.startswith("$$"):
            buf = [s]
            while not (buf[-1].endswith("$$") and (len(buf) > 1 or len(s) > 2)) and i + 1 < len(lines):
                i += 1
                buf.append(lines[i].strip())
            i += 1
            out.append(f'<div class="fs-eq">{html.escape(chr(10).join(buf), quote=False)}</div>')
        elif s.startswith("|"):
            rows = []
            while i < len(lines) and lines[i].strip().startswith("|"):
                rows.append(_cells(lines[i]))
                i += 1
            head, body = rows[0], [r for r in rows[1:] if not all(re.fullmatch(r":?-+:?", c) for c in r)]
            if [h.lower() for h in head] == ["step", "why"]:
                items = "".join(f'<div class="fs-step"><div class="fs-step-math">{inline(r[0])}</div>'
                                f'<div class="fs-why">{inline(r[1] if len(r) > 1 else "")}</div></div>' for r in body)
                out.append(f'<div class="fs-steps">{items}</div>')
            else:
                th = "".join(f"<th>{inline(c)}</th>" for c in head)
                trs = "".join("<tr>" + "".join(f"<td>{inline(c)}</td>" for c in r) + "</tr>" for r in body)
                out.append(f'<div class="table-wrapper"><table class="fs-table"><thead><tr>{th}</tr></thead>'
                           f"<tbody>{trs}</tbody></table></div>")
        elif re.match(r"(\d+\.|-)\s", s):
            ordered = s[0].isdigit()
            items = []
            while i < len(lines) and re.match(r"\s*(\d+\.|-)\s", lines[i]):
                items.append(re.sub(r"^\s*(\d+\.|-)\s+", "", lines[i].rstrip()))
                i += 1
                while i < len(lines) and lines[i].startswith("   ") and lines[i].strip():
                    items[-1] += " " + lines[i].strip()
                    i += 1
            tag = "ol" if ordered else "ul"
            out.append(f"<{tag}>" + "".join(f"<li>{inline(t)}</li>" for t in items) + f"</{tag}>")
        else:
            buf = [s]
            i += 1
            while i < len(lines) and lines[i].strip() and not re.match(r"\s*(\$\$|\||\d+\.\s|-\s|#)", lines[i]):
                buf.append(lines[i].strip())
                i += 1
            out.append(f"<p>{inline(' '.join(buf))}</p>")
    return "\n".join(out)


def render_card(title, lines, used):
    kind, _, name = title.partition(":")
    kind = kind.strip()
    if kind not in KINDS or not name.strip():
        raise ValueError(f"card heading must be '<Kind>: <title>' with Kind in {sorted(KINDS)}: {title!r}")
    name = name.strip()
    cid = slugify(name)
    while cid in used:
        cid += "-x"
    used.add(cid)
    summary = None
    body = []
    for ln in lines:
        if summary is None and ln.strip().startswith("In short:"):
            summary = ln.strip()[len("In short:"):].strip()
        else:
            body.append(ln)
    inner = render_blocks(body)
    head = (f'<h3 class="fs-card-title"><span class="fs-kind">{kind}</span> '
            f'<span class="fs-name">{inline(name)}</span></h3>')
    if kind == "Derivation":
        if not summary:
            raise ValueError(f"Derivation card without an 'In short:' line: {title!r}")
        inner = (f'<details class="fs-deriv" open><summary><span class="fs-short">In short:</span> '
                 f"{inline(summary)}</summary>\n<div class=\"fs-deriv-body\">\n{inner}\n</div></details>")
    elif summary:
        inner = f'<p class="fs-lead">{inline(summary)}</p>\n{inner}'
    return f'<article class="fs-card fs-{KINDS[kind]}" id="{cid}">\n{head}\n{inner}\n</article>'


def render_note(text):
    text = re.sub(r"\A---\n.*?\n---\n", "", text, flags=re.S)
    sections = re.split(r"^## ", text, flags=re.M)[1:]
    out, toc, used = [], [], set()
    for sec in sections:
        lines = sec.split("\n")
        title = lines[0].strip()
        sid = slugify(title)
        used.add(sid)
        links, cards, intro, cur = "", [], [], None
        for ln in lines[1:]:
            if ln.startswith("### "):
                cur = [ln[4:].strip(), []]
                cards.append(cur)
            elif cur is None:
                if ln.startswith("Pages:"):
                    parts = [p.split("=", 1) for p in ln[6:].split(";") if "=" in p]
                    links = " · ".join(f'<a href="../{html.escape(href.strip())}">{html.escape(lab.strip())}</a>'
                                       for lab, href in parts)
                else:
                    intro.append(ln)
            else:
                cur[1].append(ln)
        toc.append(f'<li><a href="#{sid}">{inline(title)}</a></li>')
        out.append(f'<section class="fs-unit" id="{sid}" aria-labelledby="{sid}-title">')
        out.append(f'<h2 class="fs-unit-title" id="{sid}-title">{inline(title)}</h2>')
        if links:
            out.append(f'<p class="fs-unit-links">{links}</p>')
        if any(x.strip() for x in intro):
            out.append(f'<div class="fs-unit-intro">{render_blocks(intro)}</div>')
        out.append('<div class="fs-grid">')
        out.extend(render_card(t, body, used) for t, body in cards)
        out.append("</div>\n</section>")
    nav = ('<nav class="fs-toc" aria-label="Formula sheet contents"><ol>' + "".join(toc) + "</ol></nav>")
    return nav + "\n" + "\n".join(out)


def build(root, slug):
    note = root / SHEETS[slug]
    page = root / "subjects" / slug / "formula-sheet" / "index.html"
    current = page.read_text(encoding="utf-8")
    a, b = current.find(START), current.find(END)
    if a < 0 or b < a:
        raise ValueError(f"{page}: FORMULA-SHEET markers not found")
    block = render_note(note.read_text(encoding="utf-8"))
    return page, current, current[:a] + START + "\n" + block + "\n" + current[b:]


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--root", default=pathlib.Path(__file__).resolve().parents[1], type=pathlib.Path)
    ap.add_argument("--check", action="store_true", help="exit 1 if a page is stale")
    args = ap.parse_args(argv)
    stale = 0
    for slug in SHEETS:
        page, current, new = build(args.root, slug)
        rel = page.relative_to(args.root).as_posix()
        if args.check:
            if current != new:
                print(f"STALE: {rel} does not match {SHEETS[slug]}. Run tools/build_formula_sheet.py")
                stale += 1
            else:
                print(f"OK: {rel} is up to date")
        elif current != new:
            with open(page, "w", encoding="utf-8", newline="\n") as fh:
                fh.write(new)
            print(f"Wrote {rel}")
        else:
            print(f"Unchanged {rel}")
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
