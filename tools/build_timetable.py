#!/usr/bin/env python3
"""Build assets/data/timetable.js (window.AE_TIMETABLE) for the account calendar.

Source of truth: the vault notes `vault/<subject>/Schedule - <Subject> 2026-27.md` (frontmatter
`calendar` = subject slug, `source`, `basis` plan|log, `term_end`; sections `## Groups`,
`## Lab groups` and `## Sessions`, each a Markdown table). Rows of kind `holiday` / `no-class`
become term days off instead of sessions. Checks: unique ids, dates inside the term, portal
links that exist (file and `#id`), and no link on a laboratory row (lab material is never
published).

Usage: python tools/build_timetable.py [--check]
"""
import json
import pathlib
import re
import sys

REPO = pathlib.Path(__file__).resolve().parents[1]
OUT = "assets/data/timetable.js"
TERM = {"start": "2026-09-07", "end": "2026-12-18"}
DAYS = {"Mon": 1, "Tue": 2, "Wed": 3, "Thu": 4, "Fri": 5, "Sat": 6, "Sun": 7}
KINDS = {"lecture", "problems", "lab", "test", "quiz", "holiday", "no-class"}
DATE_RE = re.compile(r"^\d{4}-\d{2}-\d{2}$")
TIME_RE = re.compile(r"^\d{2}:\d{2}$")
LINK_RE = re.compile(r"\[([^\]]+)\]\(([^)]+)\)")
HEADER = ("/* Generated by tools/build_timetable.py from the vault notes 'Schedule - ...'. "
          "Do not edit by hand. */\n")


def frontmatter(text, where):
    m = re.match(r"---\n(.*?)\n---\n", text, re.S)
    if not m:
        raise ValueError(f"{where}: no frontmatter")
    out = {}
    for line in m.group(1).split("\n"):
        mm = re.match(r"^([a-z_]+):\s*(.*)$", line)
        if mm and mm.group(2):
            out[mm.group(1)] = mm.group(2).strip()
    return out, text[m.end():]


def section(body, title):
    m = re.search(r"^## " + re.escape(title) + r"\s*\n(.*?)(?=^## |\Z)", body, re.S | re.M)
    return m.group(1) if m else ""


def table(text):
    rows = [l.strip() for l in text.split("\n") if l.strip().startswith("|")]
    if len(rows) < 2:
        return []
    head = [c.strip() for c in rows[0].strip("|").split("|")]
    out = []
    for r in rows[2:]:
        cells = [c.strip() for c in r.strip().strip("|").split("|")]
        if len(cells) != len(head):
            raise ValueError(f"table row has {len(cells)} cells, expected {len(head)}: {r[:60]}")
        out.append(dict(zip(head, cells)))
    return out


def check_link(root, href, where):
    path, _, anchor = href.partition("#")
    page = root / path
    if not path.startswith("subjects/") or not page.is_file():
        raise ValueError(f"{where}: portal link to a missing page: {href}")
    if anchor and f'id="{anchor}"' not in page.read_text(encoding="utf-8"):
        raise ValueError(f"{where}: no #{anchor} in {path}")


def opt(value, regex, where, field):
    if not value:
        return None
    if not regex.match(value):
        raise ValueError(f"{where}: bad {field} {value!r}")
    return value


def parse_note(root, path):
    where = path.name
    meta, body = frontmatter(path.read_text(encoding="utf-8"), where)
    slug = meta.get("calendar")
    if not slug:
        raise ValueError(f"{where}: no 'calendar' slug")
    basis = meta.get("basis", "plan")
    if basis not in ("plan", "log"):
        raise ValueError(f"{where}: basis must be plan or log")
    groups = {}
    for row in table(section(body, "Groups")):
        g = groups.setdefault(row["Group"], {"dated": row["Dated"] == "yes", "slots": []})
        if row["Day"] not in DAYS:
            raise ValueError(f"{where}: bad day {row['Day']!r}")
        g["slots"].append({"dow": DAYS[row["Day"]], "start": opt(row["Start"], TIME_RE, where, "start"),
                           "end": opt(row["End"], TIME_RE, where, "end"), "room": row["Room"] or None,
                           "kind": row["Kind"]})
    labs_text = section(body, "Lab groups").strip()
    lab_groups = [] if labs_text in ("", "none") else [x.strip() for x in labs_text.split(",")]
    sessions, days_off = [], []
    for row in table(section(body, "Sessions")):
        sid = row["Id"]
        w = f"{where} {sid}"
        kind = row["Kind"]
        if kind not in KINDS:
            raise ValueError(f"{w}: bad kind {kind!r}")
        date = opt(row["Date"], DATE_RE, w, "date")
        if date and not TERM["start"] <= date <= TERM["end"]:
            raise ValueError(f"{w}: date {date} outside the term")
        if kind in ("holiday", "no-class"):
            days_off.append({"date": date, "subjects": None if kind == "holiday" else [slug], "why": row["Title"]})
            continue
        links = [{"label": a, "href": b} for a, b in LINK_RE.findall(row["Portal"])]
        if kind == "lab" and links:
            raise ValueError(f"{w}: a laboratory row must not link anywhere")
        for link in links:
            check_link(root, link["href"], w)
        lab = row["Lab"] or None
        if lab and lab not in lab_groups:
            raise ValueError(f"{w}: lab group {lab!r} not declared")
        sessions.append({
            "id": sid, "n": int(row["N"]) if row["N"] else None, "kind": kind, "title": row["Title"],
            "text": row["What you will do"], "date": date,
            "start": opt(row["Start"], TIME_RE, w, "start"), "end": opt(row["End"], TIME_RE, w, "end"),
            "room": row["Room"] or None,
            "groups": [g.strip() for g in row["Groups"].split(",")] if row["Groups"] else None,
            "lab": lab, "links": links})
    return slug, {"name": meta.get("subject"), "source": meta.get("source"), "basis": basis,
                  "termEnd": meta.get("term_end"), "groups": groups, "labGroups": lab_groups,
                  "sessions": sessions}, days_off


def build(root=REPO):
    root = pathlib.Path(root)
    subjects, days_off, seen = {}, [], set()
    for path in sorted((root / "vault").glob("*/Schedule - *.md")):
        slug, data, off = parse_note(root, path)
        for s in data["sessions"]:
            if s["id"] in seen:
                raise ValueError(f"{path.name}: duplicate session id {s['id']}")
            seen.add(s["id"])
        subjects[slug] = data
        days_off.extend(off)
    days_off.sort(key=lambda d: d["date"])
    return {"term": dict(TERM, daysOff=days_off), "subjects": subjects}


def render(data):
    return HEADER + "window.AE_TIMETABLE = " + json.dumps(data, indent=1, ensure_ascii=False) + ";\n"


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    try:
        text = render(build(REPO))
    except ValueError as exc:
        print(f"build_timetable: {exc}")
        return 1
    out = REPO / OUT
    if "--check" in argv:
        if not out.is_file() or out.read_text(encoding="utf-8") != text:
            print(f"build_timetable: {OUT} is stale; run python tools/build_timetable.py")
            return 1
        print("build_timetable: up to date")
        return 0
    out.write_text(text, encoding="utf-8", newline="\n")
    print(f"build_timetable: wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
