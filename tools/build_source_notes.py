#!/usr/bin/env python3
"""Write one generated vault note per file under sources/, plus one index per subject.

Each note in vault/07 - Sources/ records the file's path, kind, size and status, and
lists the vault notes that cite it. A file whose status is "not-referenced" has no note
that mentions it yet, so the gap is visible in Obsidian. The notes are generated: change
the vault notes that cite a file, or tools/source_notes.json, never the generated files.

Usage:
    python tools/build_source_notes.py          # write the notes and the indexes
    python tools/build_source_notes.py --check  # exit 1 if a note is missing, stale or orphaned
"""
import argparse
import collections
import json
import pathlib
import re
import sys

TOOLS = pathlib.Path(__file__).resolve().parent
REPO = TOOLS.parent
sys.path.insert(0, str(TOOLS))

import sources_manifest as sm  # noqa: E402  (reuses the laboratory rule and the category names)

CONFIG_REL = pathlib.Path("tools", "source_notes.json")
SOURCES_REL = pathlib.Path("sources")
VAULT_REL = pathlib.Path("vault")
OUT_REL = pathlib.Path("vault", "07 - Sources")
BANNER = "Generated by `tools/build_source_notes.py`. Do not edit by hand; regenerate with `python tools/build_source_notes.py`."
STATUSES = ("referenced", "not-referenced", "build-artifact", "working-file")


def load_config(root):
    return json.loads((root / CONFIG_REL).read_text(encoding="utf-8"))


def display_name(vault_folder):
    return re.sub(r"^\d+\s*-\s*", "", vault_folder)


def human_size(n):
    for unit in ("B", "kB", "MB", "GB"):
        if n < 1000 or unit == "GB":
            return f"{n} B" if unit == "B" else f"{n:.1f} {unit}"
        n /= 1000


def collect(root, config):
    """Return one record per file under sources/ (no citations yet)."""
    sources = root / SOURCES_REL
    subjects = config["subjects"]
    root_folder = config["root_folder"]
    records = []
    files = (p for p in sources.rglob("*") if p.is_file())
    for path in sorted(files, key=lambda p: sm._natural_key(p.relative_to(sources).as_posix())):
        if path.name == ".gitkeep" or "__pycache__" in path.parts:
            continue
        parts = path.relative_to(sources).parts
        if parts[0] == "cuatrimestre-1":
            parts = parts[1:]
        if len(parts) == 1:
            folder, subject, within = root_folder, root_folder, parts
            kind = "other"
        else:
            if parts[0] not in subjects:
                raise SystemExit(f"build_source_notes: no vault folder for sources/{parts[0]} (add it to tools/source_notes.json)")
            folder = subjects[parts[0]]
            subject = display_name(folder)
            within = parts[1:]
            if sm._is_excluded(within):
                kind = "laboratorio"
            else:
                kind = next((x for x in within[:-1] if x in sm.CATEGORIES), "other")
        label = f"{path.stem} ({path.suffix[1:]})" if path.suffix else path.name
        records.append({
            "path": path.relative_to(root).as_posix(),
            "file_name": path.name,
            "name": "Source - " + " - ".join([*parts[:-1], label]),
            "folder": folder,
            "subject": subject,
            "within_dir": "/".join(within[:-1]) or "(top level)",
            "kind": kind,
            "bytes": path.stat().st_size,
            "ext": path.suffix.lower(),
        })
    counts = collections.Counter(r["file_name"] for r in records)
    for r in records:
        r["shared_with"] = counts[r["file_name"]] - 1
    names = [r["name"] for r in records]
    if len(set(names)) != len(names):
        raise SystemExit("build_source_notes: two source files map to the same note name")
    return records


def find_citations(root, records):
    """Map each source path to the vault notes that cite it.

    A full repo path counts everywhere. A bare file name counts; when that name is shared
    by several copies under sources/, a bare mention is credited only to the copies in the
    same subject as the citing note.
    """
    out_dir = root / OUT_REL
    notes = {}
    for md in sorted((root / VAULT_REL).rglob("*.md")):
        if out_dir in md.parents:
            continue
        key = md.relative_to(root / VAULT_REL).with_suffix("").as_posix()
        notes[key] = (key.split("/")[0], md.read_text(encoding="utf-8"))
    counts = collections.Counter(r["file_name"] for r in records)
    cites = {}
    for r in records:
        base = r["file_name"]
        rx = re.compile(r"(?<![\w.\-])" + re.escape(base) + r"(?![\w\-])")
        shared = counts[base] > 1
        cites[r["path"]] = sorted(
            note for note, (folder, text) in notes.items()
            if r["path"] in text or (rx.search(text) and (not shared or folder == r["folder"]))
        )
    return cites


def assign_status(records, cites, config):
    artifacts = tuple(config["build_artifact_extensions"])
    working = set(config["working_files"])
    for r in records:
        r["cited_by"] = cites[r["path"]]
        if r["ext"] in artifacts:
            r["status"] = "build-artifact"
        elif r["path"] in working:
            r["status"] = "working-file"
        else:
            r["status"] = "referenced" if r["cited_by"] else "not-referenced"


STATUS_TEXT = {
    "referenced": "referenced by {n} note(s) below",
    "not-referenced": "not referenced yet: no vault note mentions this file, so its content still has to be extracted",
    "build-artifact": "LaTeX build artifact; a candidate for removal from git (this tool does not remove it)",
    "working-file": "working file tracked in sources/; a candidate for removal from git (this tool does not remove it)",
}


def render_note(r):
    fm = [
        "---",
        f"subject: {json.dumps(r['subject'], ensure_ascii=False)}",
        "tags:",
        "  - source",
        f"  - {r['kind']}",
        f"  - {r['status']}",
        f"path: {json.dumps(r['path'], ensure_ascii=False)}",
        f"kind: {r['kind']}",
        f"status: {r['status']}",
        f"bytes: {r['bytes']}",
        "---",
    ]
    status = STATUS_TEXT[r["status"]].format(n=len(r["cited_by"]))
    body = [
        "",
        f"# Source: {r['file_name']}",
        "",
        f"> {BANNER}",
        "",
        "## Record",
        "",
        f"- **Path:** `{r['path']}`",
        f"- **Kind:** {r['kind']}",
        f"- **Size:** {human_size(r['bytes'])}",
        f"- **Status:** {status}",
    ] + ([f"- **Shared name:** the file name is shared with {r['shared_with']} other copy(ies) under `sources/`; a bare mention is credited to the notes of this subject only."] if r["shared_with"] else []) + [
        "",
        "## Referenced by",
        "",
    ]
    if r["cited_by"]:
        body += [f"- [[{note}]]" for note in r["cited_by"]]
    else:
        body.append("No vault note mentions this file yet.")
    return "\n".join(fm + body) + "\n"


def render_index(folder, subject, recs):
    counts = collections.Counter(r["status"] for r in recs)
    lines = [
        "---",
        f"subject: {json.dumps(subject, ensure_ascii=False)}",
        "tags:",
        "  - source-index",
        "---",
        "",
        f"# Sources Index - {subject}",
        "",
        f"> {BANNER}",
        "",
        "## Coverage",
        "",
        f"- Files: {len(recs)}",
    ]
    lines += [f"- {STATUS_TEXT_LABEL[s]}: {counts[s]}" for s in STATUSES]
    groups = collections.defaultdict(list)
    for r in recs:
        groups[r["within_dir"]].append(r)
    for key in sorted(groups, key=sm._natural_key):
        lines += ["", f"## {key}", "", "| File | Kind | Status |", "| :--- | :--- | :--- |"]
        for r in sorted(groups[key], key=lambda r: sm._natural_key(r["file_name"])):
            lines.append(f"| [[{r['name']}\\|{r['file_name']}]] | {r['kind']} | {r['status']} |")
    return "\n".join(lines) + "\n"


STATUS_TEXT_LABEL = {
    "referenced": "Referenced by at least one note (a mention counts)",
    "not-referenced": "Not referenced yet",
    "build-artifact": "Build artifacts",
    "working-file": "Working files",
}


def plan(root, config):
    """Return ({repo-relative path: text}, summary) for every generated note and index."""
    records = collect(root, config)
    cites = find_citations(root, records)
    assign_status(records, cites, config)
    desired = {}
    for r in records:
        rel = (OUT_REL / r["folder"] / f"{r['name']}.md").as_posix()
        desired[rel] = render_note(r)
    by_folder = collections.defaultdict(list)
    for r in records:
        by_folder[(r["folder"], r["subject"])].append(r)
    for (folder, subject), recs in by_folder.items():
        rel = (OUT_REL / folder / f"Sources Index - {subject}.md").as_posix()
        desired[rel] = render_index(folder, subject, recs)
    counts = collections.Counter(r["status"] for r in records)
    summary = (f"{len(records)} notes ({counts['referenced']} referenced, {counts['not-referenced']} not referenced, "
               f"{counts['build-artifact']} build artifacts, {counts['working-file']} working files) "
               f"and {len(by_folder)} indexes")
    return desired, summary


def existing_notes(root):
    out_dir = root / OUT_REL
    if not out_dir.exists():
        return {}
    return {p.relative_to(root).as_posix(): p for p in out_dir.rglob("*.md")}


def check(root, desired):
    problems = []
    for rel, text in sorted(desired.items()):
        path = root / rel
        if not path.exists():
            problems.append(f"missing {rel}")
        elif path.read_text(encoding="utf-8") != text:
            problems.append(f"stale {rel}")
    for rel in sorted(set(existing_notes(root)) - set(desired)):
        problems.append(f"orphan {rel}")
    return problems


def write(root, desired):
    """Write the generated notes and delete orphans that carry the banner. Return refused orphans."""
    for rel, text in desired.items():
        path = root / rel
        if path.exists() and path.read_text(encoding="utf-8") == text:
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    refused = []
    for rel, path in existing_notes(root).items():
        if rel in desired:
            continue
        if BANNER in path.read_text(encoding="utf-8"):
            path.unlink()
        else:
            refused.append(rel)
    return refused


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="exit 1 if a note is missing, stale or orphaned")
    ap.add_argument("--root", type=pathlib.Path, default=REPO)
    args = ap.parse_args(argv)
    root = args.root.resolve()
    desired, summary = plan(root, load_config(root))
    if args.check:
        problems = check(root, desired)
        for p in problems:
            print(p)
        if problems:
            print(f"build_source_notes: {len(problems)} problem(s) (run python tools/build_source_notes.py)")
            return 1
        print(f"build_source_notes: {summary} up to date")
        return 0
    refused = write(root, desired)
    if refused:
        for rel in refused:
            print(f"not generated, remove by hand: {rel}")
        return 1
    print(f"build_source_notes: wrote {summary}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
